    private void jUpdateSystemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jUpdateSystemActionPerformed
        // TODO add your handling code here:
        String currentIdText = jCurrentSystemTextfeild.getText().trim();
        String newIdText = jNewSystemTextfeild.getText().trim();

        if (currentIdText.isEmpty() || newIdText.isEmpty()) {
            jMessage.setText("Please enter data");
            return;
        }

        int currentId, newId;

        //Convert it to an integer for the ID
        try {
            currentId = Integer.parseInt(currentIdText);
            newId = Integer.parseInt(newIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("System IDs must be numbers");
            return;
        }

        TrafficSystemDAO systemDAO = new TrafficSystemDAO();

        //Before adding the system, make sure that the id doesn't exist in the database
        int updateStatus = -1;

        try {
            if (systemDAO.findTrafficSystemByID(currentId) == null) {
                jMessage.setText("System does not exist in the DB");
                return;
            }

            //Update system
            updateStatus = systemDAO.updateTrafficSystem(currentId, newId);

            if (updateStatus == 1) {
                jMessage.setText("System " + currentId + " is updated to " + newId + "!");
                jCurrentSystemTextfeild.setText("");
                jNewSystemTextfeild.setText("");
                loadAllSystem();
            } else {
                jMessage.setText("No record is updated");
            }

        } catch (SQLException e) {
            jMessage.setText(e.getMessage());
        }
    }//GEN-LAST:event_jUpdateSystemActionPerformed

    private void jDeleteSystemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jDeleteSystemActionPerformed
        // TODO add your handling code here:
        String systemIdText = jCurrentSystemTextfeild.getText().trim();

        if (systemIdText.isEmpty()) {
            jMessage.setText("Please enter the System ID to delete");
            return;
        }

        int systemId;

        //Convert it to an integer for the ID
        try {
            systemId = Integer.parseInt(systemIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("System ID must be a number");
            return;
        }

        TrafficSystemDAO systemDAO = new TrafficSystemDAO();
        int deleteStatus = -1;

        //Check if ID exist
        try {
            if (systemDAO.findTrafficSystemByID(systemId) == null) {
                jMessage.setText("System ID does not exist in the DB");
                return;
            }

            //Delete system
            deleteStatus = systemDAO.deleteTrafficSystem(systemId);

        } catch (SQLException e) {
            jMessage.setText(e.getMessage());
        }

        if (deleteStatus == 1) {
            jMessage.setText("System " + systemId + " is deleted!");
            jCurrentSystemTextfeild.setText("");
            loadAllSystem();
        } else {
            jMessage.setText("Error while deleting system " + systemId);
        }
    }//GEN-LAST:event_jDeleteSystemActionPerformed

    private void loadAllSystem() {
        //step 1:  set the column name of the jtable
        Vector colNameV = new Vector();
        colNameV.add("System ID");

        //Step 2: set the rows of jtable
        //2.a retreive all program data
        TrafficSystemDAO systemDAO = new TrafficSystemDAO();
        List<TrafficSystem> systemList = null;
        try {
            systemList = systemDAO.getAllTrafficSystems();
        } catch (SQLException e) {
            jMessage.setText("Database Error! " + e.getMessage());
        }

        //convert the programList and data in it to a vector of vectors
        Vector rowDataVector = new Vector();
        Vector cellVector = null;

        for (TrafficSystem s : systemList) {
            cellVector = new Vector();
            cellVector.add(s.getSystemID());
            //add this cell data vector to the rowDataVector
            rowDataVector.add(cellVector);
        }

        //init the JTable instance using the row data and column data vectors
        jSystemTable = new JTable(rowDataVector, colNameV);
        jScrollPane1.setViewportView(jSystemTable);
    }

