    private void jAddSystemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jAddSystemActionPerformed
        // TODO add your handling code here:
        String systemIdText = jNewSystemTextfeild.getText().trim();

        if (systemIdText.isEmpty()) {
            jMessage.setText("Please enter data");
            return;
        }

        //Convert it to an integer for the ID
        int systemId;
        try {
            systemId = Integer.parseInt(systemIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("System ID must be a number");
            return;
        }

        TrafficSystemDAO systemDAO = new TrafficSystemDAO();

        //Make sure that the ID doesn't exist in the database before adding
        try {
            if (systemDAO.findTrafficSystemByID(systemId) != null) {
                jMessage.setText("System ID exists in the DB");
                return;
            }

            //Add new system
            int insertStatus = systemDAO.addNewTrafficSystem(systemId);
            jMessage.setText("System " + systemId + " is added!");
            jNewSystemTextfeild.setText("");
            loadAllSystem();

        } catch (SQLException e) {
            jMessage.setText(e.getMessage());
        }
    }//GEN-LAST:event_jAddSystemActionPerformed

