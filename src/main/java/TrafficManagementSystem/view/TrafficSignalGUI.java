    private void jDeleteSignalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jDeleteSignalActionPerformed
        // TODO add your handling code here:
        String signalIdText = jSignalIDText.getText().trim();

        if (signalIdText.isEmpty()) {
            jMessage.setText("Enter a Signal ID.");
            return;
        }

        int signalId;

        try {
            signalId = Integer.parseInt(signalIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("Signal ID must be a number.");
            return;
        }

        TrafficSignalDAO signalDAO = new TrafficSignalDAO();
        int deleteStatus = -1;

        try {
            if (signalDAO.findSignalById(signalId) == null) {
                jMessage.setText("Signal not found.");
                return;
            }

            deleteStatus = signalDAO.deleteSignal(signalId);

        } catch (SQLException e) {
            jMessage.setText(e.getMessage());
        }

        if (deleteStatus == 1) {
            jMessage.setText("Signal " + signalId + " is deleted!");
            jSignalIDText.setText("");
            loadAllSignals();
        } else {
            jMessage.setText("Error while deleting signal " + signalId);
        }
    }//GEN-LAST:event_jDeleteSignalActionPerformed

