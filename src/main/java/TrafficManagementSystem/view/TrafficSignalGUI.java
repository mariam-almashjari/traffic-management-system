    private void jViewSignalByLocationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jViewSignalByLocationActionPerformed
        // TODO add your handling code here:
        String systemIdText = jSystemIDText.getText().trim();
        String location = jLocationText.getText().trim();
        
        if(systemIdText.isEmpty() || location.isEmpty()){
            jMessage.setText("Enter system ID and location.");
            return;
        }
        
        int systemId;
        
        try{
            systemId = Integer.parseInt(systemIdText);
        }catch(NumberFormatException e){
            jMessage.setText("System ID must be a number.");
            return;
        }
        
        Vector colNameV = new Vector();
        colNameV.add("Signal ID");
        colNameV.add("Location");
        colNameV.add("State");
        colNameV.add("System ID");
        
        TrafficSignalDAO signalDAO = new TrafficSignalDAO();
        List<TrafficSignal> signalList = null;
        try {
            signalList = signalDAO.getAllSignals(systemId, location);
        } catch (SQLException e) {
            jMessage.setText("Database Error! " + e.getMessage());
        }
        
        Vector rowDataVector = new Vector();
        Vector cellVector = null;

        for (TrafficSignal s : signalList) {
            cellVector = new Vector();
            cellVector.add(s.getID());
            cellVector.add(s.getLocation());
            cellVector.add(s.getState());
            cellVector.add(s.getSystemId());
            rowDataVector.add(cellVector);
        }
        
        jSignalTable = new JTable(rowDataVector, colNameV);
        jScrollPane1.setViewportView(jSignalTable);
        jSystemIDText.setText("");
        jSignalIDText.setText("");
        jLocationText.setText("");
        jStateCombo.setSelectedIndex(0);
    }//GEN-LAST:event_jViewSignalByLocationActionPerformed

    private void loadAllSignals() {
        //set the column name of the jtable
        Vector colNameV = new Vector();
        colNameV.add("Signal ID");
        colNameV.add("Location");
        colNameV.add("State");
        colNameV.add("System ID");

        //set the rows of jtable
        //a retreive all signal data
        TrafficSignalDAO signalDAO = new TrafficSignalDAO();
        List<TrafficSignal> signalList = null;
        try {
            signalList = signalDAO.getAllSignals();
        } catch (SQLException e) {
            jMessage.setText("Database Error! " + e.getMessage());
        }

        //convert the signalList and data in it to a vector of vectors
        Vector rowDataVector = new Vector();
        Vector cellVector = null;

        for (TrafficSignal s : signalList) {
            cellVector = new Vector();
            cellVector.add(s.getID());
            cellVector.add(s.getLocation());
            cellVector.add(s.getState());
            cellVector.add(s.getSystemId());
            rowDataVector.add(cellVector);
        }

        //init the JTable instance using the row data and column data vectors
        jSignalTable = new JTable(rowDataVector, colNameV);
        jScrollPane1.setViewportView(jSignalTable);
    }

