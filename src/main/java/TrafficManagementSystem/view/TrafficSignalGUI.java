    private void jAddSignalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jAddSignalActionPerformed
        // TODO add your handling code here:
        String systemIdText = jSystemIDText.getText().trim();
        String signalIdText = jSignalIDText.getText().trim();
        String location = jLocationText.getText().trim();
        String state = jStateCombo.getSelectedItem().toString();

        if (systemIdText.isEmpty() || signalIdText.isEmpty() || location.isEmpty()) {
            jMessage.setText("Please enter all fields.");
            return;
        }

        int systemId;
        int signalId;

        try {
            systemId = Integer.parseInt(systemIdText);
            signalId = Integer.parseInt(signalIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("System ID and Signal ID must be numbers.");
            return;
        }

        TrafficSignalDAO signalDAO = new TrafficSignalDAO();
        TrafficSystemDAO systemDAO = new TrafficSystemDAO();

        try {
            if (systemDAO.findTrafficSystemByID(systemId) == null) {
                jMessage.setText("System ID does not exist.");
                return;
            }

            if (signalDAO.findSignalById(signalId) != null) {
                jMessage.setText("Signal ID already exists.");
                return;
            }

            int result = signalDAO.addNewSignal(signalId, location, state, systemId);

            if (result == 1) {
                jMessage.setText("Signal added successfully.");
                jSystemIDText.setText("");
                jSignalIDText.setText("");
                jLocationText.setText("");
                jStateCombo.setSelectedIndex(0);
                loadAllSignals();
            } else {
                jMessage.setText("Error adding signal.");
            }

        } catch (SQLException e) {
            jMessage.setText(e.getMessage());
        }
    }//GEN-LAST:event_jAddSignalActionPerformed

