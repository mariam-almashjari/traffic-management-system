    private void jViewSensorByLocationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jViewSensorByLocationActionPerformed
        // TODO add your handling code here:
        String systemIdText = jSystemIDTextfeild.getText().trim();
        String location = jSensorLocationTextfeild.getText().trim();

        if (systemIdText.isEmpty() || location.isEmpty()) {
            jMessage.setText("Enter system ID and location.");
            return;
        }

        int systemId;

        try {
            systemId = Integer.parseInt(systemIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("System ID must be a number.");
            return;
        }

        Vector colNameV = new Vector();
        colNameV.add("Sensor ID");
        colNameV.add("Location");
        colNameV.add("Status");
        colNameV.add("System ID");

        TrafficSensorDAO dao = new TrafficSensorDAO();
        List<TrafficSensor> sensorList = null;

        try {
            sensorList = dao.getAllSensors(systemId, location);
        } catch (SQLException e) {
            jMessage.setText("Database Error! " + e.getMessage());
        }

        Vector rowDataVector = new Vector();
        Vector cellVector = null;

        for (TrafficSensor s : sensorList) {
            cellVector = new Vector();
            cellVector.add(s.getID());
            cellVector.add(s.getLocation());
            cellVector.add(s.getStatus());
            cellVector.add(s.getSystemId());
            rowDataVector.add(cellVector);
        }

        jSensorTable = new JTable(rowDataVector, colNameV);
        jScrollPane1.setViewportView(jSensorTable);
        jSystemIDTextfeild.setText(""); 
        jSensorIDTextfeild.setText(""); 
        jSensorLocationTextfeild.setText(""); 
        jStatusComboBox.setSelectedIndex(0);
    }//GEN-LAST:event_jViewSensorByLocationActionPerformed

    private void loadAllSensors() {
        //step 1:  set the column name of the jtable
        Vector colNameV = new Vector();
        colNameV.add("Sensor ID");
        colNameV.add("Location");
        colNameV.add("Status");
        colNameV.add("System ID");

        //Step 2: set the rows of jtable
        //2.a retreive all sensor data
        TrafficSensorDAO sensorDAO = new TrafficSensorDAO();
        List<TrafficSensor> sensorList = null;
        try {
            sensorList = sensorDAO.getAllSensors();
        } catch (SQLException e) {
            jMessage.setText("Database Error! " + e.getMessage());
        }

        //convert the sensorList and data in it to a vector of vectors
        Vector rowDataVector = new Vector();
        Vector cellVector = null;

        for (TrafficSensor s : sensorList) {
            cellVector = new Vector();
            cellVector.add(s.getID());
            cellVector.add(s.getLocation());
            cellVector.add(s.getStatus());
            cellVector.add(s.getSystemId()); // ✅ FIXED
            rowDataVector.add(cellVector);
        }

        //init the JTable instance using the row data and column data vectors
        jSensorTable = new JTable(rowDataVector, colNameV);
        jScrollPane1.setViewportView(jSensorTable);
    }

