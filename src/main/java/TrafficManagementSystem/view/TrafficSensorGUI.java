    private void jDeleteSensorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jDeleteSensorActionPerformed
        // TODO add your handling code here:
        String sensorIdText = jSensorIDTextfeild.getText().trim();

        if (sensorIdText.isEmpty()) {
            jMessage.setText("Enter a Sensor ID.");
            return;
        }

        int sensorId;

        try {
            sensorId = Integer.parseInt(sensorIdText);
        } catch (NumberFormatException e) {
            jMessage.setText("Sensor ID must be a number.");
            return;
        }

        TrafficSensorDAO dao = new TrafficSensorDAO();
        int deleteStatus = -1;

        try {
            if (dao.findSensorById(sensorId) == null) {
                jMessage.setText("Sensor not found.");
                return;
            }

            deleteStatus = dao.deleteSensor(sensorId);

        } catch (SQLException e) {
            jMessage.setText(e.getMessage());
        }

        if (deleteStatus == 1) {
            jMessage.setText("Sensor " + sensorId + " is deleted!");
            jSensorIDTextfeild.setText("");
            loadAllSensors();
        } else {
            jMessage.setText("Error while deleting sensor " + sensorId);
        }
    }//GEN-LAST:event_jDeleteSensorActionPerformed

